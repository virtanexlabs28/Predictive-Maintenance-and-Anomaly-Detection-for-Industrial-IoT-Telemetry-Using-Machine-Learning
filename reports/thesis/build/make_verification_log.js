/* Writes ../reference_verification.md from references.json.  Run:  node make_verification_log.js */

const fs = require("fs");
const path = require("path");

const references = JSON.parse(fs.readFileSync(path.join(__dirname, "references.json"), "utf8"));
const chapters = ["chapter2.js", "chapter3.js", "chapter4.js", "chapter1.js", "chapter5.js"].filter((f) => fs.existsSync(path.join(__dirname, f)));
const usedIn = {};
for (const file of chapters) {
  const text = fs.readFileSync(path.join(__dirname, file), "utf8");
  for (const match of text.matchAll(/\{cite:([^}]+)\}/g)) {
    for (const key of match[1].split(",").map((k) => k.trim())) {
      (usedIn[key] = usedIn[key] || new Set()).add(file.replace("chapter", "").replace(".js", ""));
    }
  }
}

const lines = [
  "# Reference Verification Log",
  "",
  "Generated by `node make_verification_log.js` from `build/references.json`.",
  "",
  "Rule followed: a reference is cited only for statements that were checked against the source",
  "named in the last column. Where only an abstract or a secondary source could be read, the",
  "statement in the thesis is limited to what that text says.",
  "",
  "## References cited",
  "",
  "| Key | Reference | Cited in chapter | How it was checked |",
  "|---|---|---|---|",
];
for (const [key, entry] of Object.entries(references)) {
  const where = usedIn[key] ? [...usedIn[key]].sort().join(", ") : "not cited yet";
  lines.push(`| ${key} | ${entry.ieee.replace(/\*/g, "").replace(/\|/g, "/")} | ${where} | ${entry.verified} |`);
}
lines.push(
  "",
  "## Statements deliberately limited",
  "",
  "- **Reported RMSE values of earlier studies (Table 2.1).** The values for Babu et al., Zhang et al., Zheng et al. and",
  "  Li et al. are taken from the comparison table of Hou et al. (2020), whose full text was read. They were not checked",
  "  against the original papers, which are behind paywalls. The table note says so. For Li et al. two compilations",
  "  disagree (12.61 and 13.32 for FD001); both values are given.",
  "- **Limit of 130 cycles used by Heimes (2008)** and **per-condition standardisation used by Peel (2008)** are cited",
  "  through the review of Ramasso and Saxena (2014), whose full text was read, not from the original papers.",
  "- **Piecewise linear RUL target.** Described through Hou et al. (2020) and Laredo et al. (2019). No claim is made",
  "  about who first proposed it.",
  "- **Li et al. (2018).** Not read. Described only through Laredo et al. (2019) and a publisher abstract snippet.",
  "- **Jardine et al. (2006) and Lei et al. (2018).** Publisher pages could not be opened; statements are limited to",
  "  abstract text found in catalogue and university records.",
  "- **Preprints.** Galili and Meilijson (2016), Paupério et al. (2025) and Goel et al. (2026) are arXiv preprints and",
  "  are identified as such in the reference list; Goel et al. is also described as not peer reviewed in the text.",
  "- **Research gaps** are stated with respect to the sources reviewed, not as claims about the whole literature.",
  "",
  "## Checked but not cited",
  "",
  "- Ramasso, \"Investigating computational geometry for failure prognostics\", IJPHM 5(1), 2014: known only from the",
  "  reference list of Laredo et al. (2019).",
  "- Lee, Bagheri and Kao, Manufacturing Letters 3, 2015: metadata confirmed, no abstract obtained, not needed.",
  "- Qin et al., arXiv:2202.10916: comparison table read; consistent with Hou et al. for Zheng and Li; not cited.",
  "",
);
fs.writeFileSync(path.join(__dirname, "..", "reference_verification.md"), lines.join("\n"), "utf8");
console.log(`written reference_verification.md (${Object.keys(references).length} references)`);
